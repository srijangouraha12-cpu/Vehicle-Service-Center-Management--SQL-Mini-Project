-- Vehicle Service Center Management


CREATE DATABASE IF NOT EXISTS vehicle_service_center_management;
USE vehicle_service_center_management;

CREATE TABLE CUSTOMER (
    C_ID INT PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    ADDRESS VARCHAR(50) UNIQUE
);

CREATE TABLE CUSTOMER_PHONE (
    C_ID INT,
    PHONE_NO VARCHAR(10),
    FOREIGN KEY (C_ID) REFERENCES CUSTOMER(C_ID),
    PRIMARY KEY (C_ID, PHONE_NO)
);

CREATE TABLE VEHICLE (
    V_ID INT PRIMARY KEY,
    REGISTRATION_NO VARCHAR(50) NOT NULL UNIQUE,
    BRAND VARCHAR(50) NOT NULL,
    MODEL VARCHAR(50) NOT NULL,
    YEAR INT CHECK (YEAR >= 1990),
    CUSTOMER_ID INT,
    FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(C_ID)
);

CREATE TABLE MECHANIC (
    M_ID INT PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL,
    SPECIALIZATION VARCHAR(50) NOT NULL,
    SALARY DECIMAL(7,2) DEFAULT 30000.00
);

CREATE TABLE MECHANIC_PHONE (
    M_ID INT,
    M_PHONE VARCHAR(10),
    PRIMARY KEY (M_ID, M_PHONE),
    FOREIGN KEY (M_ID) REFERENCES MECHANIC(M_ID)
);

CREATE TABLE SERVICE (
    S_ID INT PRIMARY KEY,
    S_TYPE VARCHAR(50) NOT NULL,
    S_DATE_TIME DATETIME NOT NULL,
    S_COST DECIMAL(7,2),
    SPARE_PART_ID INT,
    M_ID INT,
    V_ID INT,
    FOREIGN KEY (M_ID) REFERENCES MECHANIC(M_ID),
    FOREIGN KEY (V_ID) REFERENCES VEHICLE(V_ID)
);

CREATE TABLE SPARE_PART (
    P_ID INT PRIMARY KEY,
    P_NAME VARCHAR(50),
    PRICE DECIMAL(10,2) CHECK (PRICE >= 0),
    STOCK INT CHECK (STOCK >= 0)
);

CREATE TABLE SERVICE_PART (
    PART_ID INT,
    SERVICE_ID INT,
    QUANTITY INT CHECK (QUANTITY >= 0),
    PRIMARY KEY (PART_ID, SERVICE_ID),
    FOREIGN KEY (PART_ID) REFERENCES SPARE_PART(P_ID),
    FOREIGN KEY (SERVICE_ID) REFERENCES SERVICE(S_ID)
);

CREATE TABLE SUPPLIER (
    SUPP_ID INT PRIMARY KEY,
    SUPP_NAME VARCHAR(50) NOT NULL,
    SUPP_ADDRESS VARCHAR(50) NOT NULL
);

CREATE TABLE SUPPLIER_PHONE (
    SUPP_ID INT,
    SUPP_PHONE VARCHAR(10),
    PRIMARY KEY (SUPP_ID, SUPP_PHONE),
    FOREIGN KEY (SUPP_ID) REFERENCES SUPPLIER(SUPP_ID)
);

CREATE TABLE PURCHASE (
    PURCHASE_DATE_TIME DATETIME NOT NULL,
    SUPP_ID INT,
    P_ID INT,
    PURCHASED INT,
    PRIMARY KEY (PURCHASE_DATE_TIME, SUPP_ID, P_ID),
    FOREIGN KEY (P_ID) REFERENCES SPARE_PART(P_ID),
    FOREIGN KEY (SUPP_ID) REFERENCES SUPPLIER(SUPP_ID)
);

CREATE TABLE BILL (
    S_ID INT,
    BILL_NO INT,
    BILL_DATE_TIME DATETIME NOT NULL,
    PRIMARY KEY (S_ID, BILL_NO),
    FOREIGN KEY (S_ID) REFERENCES SERVICE(S_ID)
);
