-- Vehicle Service Center Management: Task 4 queries


USE vehicle_service_center_management;

-- 1. Show all services with vehicle registration.
SELECT S.S_ID, S.S_TYPE, S.S_DATE_TIME, V.REGISTRATION_NO
FROM SERVICE AS S
JOIN VEHICLE AS V ON S.V_ID = V.V_ID;

-- 2. Display services costing more than 1800 after 5 March 2026.
SELECT *
FROM SERVICE
WHERE S_COST > 1800
  AND S_DATE_TIME > '2026-03-05';

-- 3. Arrange services by service cost in descending order.
SELECT S_ID, S_TYPE, S_DATE_TIME, S_COST
FROM SERVICE
ORDER BY S_COST DESC;

-- 4. Show services along with mechanic names.
SELECT S.S_ID, S.S_TYPE, S.S_DATE_TIME, M.NAME AS MECHANIC_NAME
FROM SERVICE AS S
JOIN MECHANIC AS M ON S.M_ID = M.M_ID;

-- 5. Find total number of services done by each mechanic.
SELECT M.NAME, COUNT(S.S_ID) AS TOTAL_SERVICES
FROM MECHANIC AS M
LEFT JOIN SERVICE AS S ON M.M_ID = S.M_ID
GROUP BY M.M_ID, M.NAME;

-- 6. Find total parts used in each service.
SELECT S.S_ID, S.S_TYPE, SUM(SP.QUANTITY) AS TOTAL_PARTS_USED
FROM SERVICE AS S
LEFT JOIN SERVICE_PART AS SP ON S.S_ID = SP.SERVICE_ID
GROUP BY S.S_ID, S.S_TYPE;

-- 7. Find least and most expensive spare part.
(SELECT P_ID, P_NAME, PRICE
 FROM SPARE_PART
 ORDER BY PRICE ASC
 LIMIT 1)
UNION ALL
(SELECT P_ID, P_NAME, PRICE
 FROM SPARE_PART
 ORDER BY PRICE DESC
 LIMIT 1);

-- 8.1 Find suppliers supplying more than 10 parts.
SELECT SU.SUPP_ID, SU.SUPP_NAME, SU.SUPP_ADDRESS,
       SUM(PU.PURCHASED) AS TOTAL_SUPPLIED
FROM SUPPLIER AS SU
JOIN PURCHASE AS PU ON SU.SUPP_ID = PU.SUPP_ID
GROUP BY SU.SUPP_ID, SU.SUPP_NAME, SU.SUPP_ADDRESS
HAVING SUM(PU.PURCHASED) > 10;

-- 8.2 Find suppliers supplying less than 10 parts.
SELECT SU.SUPP_ID, SU.SUPP_NAME, SU.SUPP_ADDRESS,
       SUM(PU.PURCHASED) AS TOTAL_SUPPLIED
FROM SUPPLIER AS SU
JOIN PURCHASE AS PU ON SU.SUPP_ID = PU.SUPP_ID
GROUP BY SU.SUPP_ID, SU.SUPP_NAME, SU.SUPP_ADDRESS
HAVING SUM(PU.PURCHASED) < 10;

-- 9. Display vehicles and total services done on each vehicle.
SELECT V.REGISTRATION_NO, COUNT(S.S_ID) AS TOTAL_SERVICES
FROM VEHICLE AS V
LEFT JOIN SERVICE AS S ON V.V_ID = S.V_ID
GROUP BY V.V_ID, V.REGISTRATION_NO;

-- 10. Display total purchase quantity of each spare part.
SELECT P.P_NAME, SUM(PU.PURCHASED) AS TOTAL_PURCHASED
FROM SPARE_PART AS P
JOIN PURCHASE AS PU ON P.P_ID = PU.P_ID
GROUP BY P.P_ID, P.P_NAME;

-- 11. Find the mechanic who generated the highest service revenue.
SELECT M.NAME AS MECHANIC_NAME,
       SUM(S.S_COST) AS TOTAL_REVENUE
FROM MECHANIC AS M
JOIN SERVICE AS S ON M.M_ID = S.M_ID
GROUP BY M.M_ID, M.NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 1;

-- 12. Find the most used spare part.
SELECT P.P_NAME, SUM(SP.QUANTITY) AS TOTAL_USED
FROM SPARE_PART AS P
JOIN SERVICE_PART AS SP ON P.P_ID = SP.PART_ID
GROUP BY P.P_ID, P.P_NAME
ORDER BY TOTAL_USED DESC
LIMIT 1;

-- 13.1 Find average stock of spare parts.
SELECT AVG(STOCK) AS AVERAGE_STOCK
FROM SPARE_PART;

-- 13.2 Find spare parts whose stock is below average.
SELECT P_NAME, STOCK
FROM SPARE_PART
WHERE STOCK < (SELECT AVG(STOCK) FROM SPARE_PART);

-- 14. Estimate monthly earnings from service cost and used-part quantities.
-- The report screenshot appears to calculate service cost plus quantity * part price.
SELECT DATE_FORMAT(S.S_DATE_TIME, '%Y-%m') AS SERVICE_MONTH,
       SUM(S.S_COST + COALESCE(SP.QUANTITY * P.PRICE, 0)) AS MONTHLY_REVENUE
FROM SERVICE AS S
LEFT JOIN SERVICE_PART AS SP ON S.S_ID = SP.SERVICE_ID
LEFT JOIN SPARE_PART AS P ON SP.PART_ID = P.P_ID
GROUP BY DATE_FORMAT(S.S_DATE_TIME, '%Y-%m')
ORDER BY SERVICE_MONTH;

-- 15. Show top 3 highest-paying customers.
SELECT C.NAME, SUM(S.S_COST) AS TOTAL_SPENT
FROM CUSTOMER AS C
JOIN VEHICLE AS V ON C.C_ID = V.CUSTOMER_ID
JOIN SERVICE AS S ON V.V_ID = S.V_ID
GROUP BY C.C_ID, C.NAME
ORDER BY TOTAL_SPENT DESC
LIMIT 3;
